// Bundles the rules engine (ocgcore WebAssembly + controller + AI) into one
// script:
//   public/engine/engine.js                         Web Worker for the browser build
//   src/features/engine/generated/engineSource.ts   the same code as a string for
//                                                   the hidden WebView on iOS
// The WebAssembly binary is embedded (base64) by ocgcore-wasm's sync build.
import fs from 'node:fs';
import path from 'node:path';

import { build } from 'esbuild';

const result = await build({
  entryPoints: ['src/features/engine/worker/entry.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020', 'safari15'],
  minify: true,
  write: false,
  legalComments: 'none',
  // The engine never loads files by URL (the wasm binary is embedded), but the
  // Emscripten glue computes a base URL when it starts.
  define: { 'import.meta.url': '"https://engine.invalid/engine.js"' },
  // Only the synchronous build is used; leave out the JSPI variant (another ~1.3 MB).
  plugins: [
    {
      name: 'skip-jspi',
      setup(b) {
        b.onResolve({ filter: /ocgcore\.jspi/ }, (args) => ({ path: args.path, namespace: 'skip-jspi' }));
        b.onLoad({ filter: /.*/, namespace: 'skip-jspi' }, () => ({ contents: 'export default undefined;', loader: 'js' }));
      },
    },
  ],
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;
const banner = '/* YGO Trainer rules engine: EDOPro ocgcore (AGPL-3.0) via ocgcore-wasm (MIT) */\n';

fs.mkdirSync('public/engine', { recursive: true });
fs.writeFileSync('public/engine/engine.js', banner + code);

const generated = path.join('src/features/engine/generated');
fs.mkdirSync(generated, { recursive: true });
fs.writeFileSync(
  path.join(generated, 'engineSource.ts'),
  `// Generated by scripts/build-engine.mjs – do not edit.\n// eslint-disable-next-line\nexport default ${JSON.stringify(banner + code)};\n`
);
console.log(`engine bundle: ${(code.length / 1024 / 1024).toFixed(2)} MB`);
